def hitung_percentile(data, persentase):

    # Menghitung posisi persentil
    posisi = (len(data) - 1) * persentase

    # Mengambil indeks bawah
    indeks_bawah = int(posisi)

    # Mengambil indeks atas
    indeks_atas = min(indeks_bawah + 1, len(data) - 1)

    # Menghitung jarak desimal
    pecahan = posisi - indeks_bawah

    # Menghitung nilai percentile dengan interpolasi
    hasil = (
        data[indeks_bawah] +
        pecahan * (data[indeks_atas] - data[indeks_bawah])
    )

    return hasil

